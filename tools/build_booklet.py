def main():
    # گذر اول: تعیین شمارهٔ صفحات فهرست
    pdf = build()
    toc = list(pdf.toc)

    # گذر دوم: درج فهرست واقعی
    pdf2 = build()

    # فهرست را روی صفحهٔ ۲ رسم می‌کنیم
    pdf2.page = 2
    y = pdf2.toc_placeholder_y
    pdf2.set_y(y)
    for title, pageno in toc:
        pdf2.set_font("Vazir", "", 11)
        pdf2.set_text_color(*NAVY)
        yy = pdf2.get_y()
        pdf2.set_xy(pdf2.l_margin, yy)
        pdf2.cell(14, 9, f"{pageno}", align="L")
        pdf2.set_xy(pdf2.l_margin + 16, yy)
        dots_w = pdf2.epw - 16
        pdf2.cell(dots_w, 9, title, align="R")
        pdf2.set_draw_color(*LINE)
        pdf2.set_line_width(0.2)
        pdf2.ln(9.6)
    pdf2.page = pdf2.pages_count

    pdf2.output(OUT)
    print("ساخته شد:", OUT)


if __name__ == "__main__":
    main()
