from fpdf import FPDF
from fpdf.enums import XPos, YPos
from fpdf.fonts import FontFace
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
FONTS = os.path.join(HERE, "fonts")
ASSETS = os.path.join(HERE, "assets")
OUT = os.path.join(ROOT, "جزوه-شب-امتحانی-آداب-پزشکی-1.pdf")

# ---------- رنگ‌ها ----------
NAVY = (23, 42, 76)
COVER_BG = (0, 1, 19)          # هم‌رنگ پس‌زمینهٔ لوگوی HumsYar
TEAL = (0, 128, 128)
TEAL_DARK = (0, 96, 100)
TEAL_BRIGHT = (0, 210, 220)
TEAL_LIGHT = (224, 242, 241)
GOLD = (240, 173, 30)
GOLD_LIGHT = (255, 248, 229)
GRAY = (90, 98, 110)
LINE = (205, 215, 220)
WHITE = (255, 255, 255)
RED = (192, 57, 43)
RED_LIGHT = (253, 237, 236)

LH = 6.6          # ارتفاع خط متن
BODY = 10.3       # اندازه قلم متن
CH_DIGITS = ["۱", "۲", "۳", "۴", "۵", "۶", "۷"]
NUM_DIGITS = ["۱", "۲", "۳", "۴", "۵", "۶", "۷", "۸", "۹", "۱۰", "۱۱", "۱۲"]


class Booklet(FPDF):
    def __init__(self):
        super().__init__("P", "mm", "A4")
        self.add_font("Vazir", "", os.path.join(FONTS, "Vazirmatn-Regular.ttf"))
        self.add_font("Vazir", "B", os.path.join(FONTS, "Vazirmatn-Bold.ttf"))
        self.add_font("VazirBlack", "", os.path.join(FONTS, "Vazirmatn-Black.ttf"))
        self.add_font("VazirLight", "", os.path.join(FONTS, "Vazirmatn-Light.ttf"))
        self.set_text_shaping(True)
        self.set_margins(16, 18, 16)
        self.set_auto_page_break(True, margin=20)
        self.toc = []
        self.chapter_no = 0

    # ---------- سربرگ و پاصفحه ----------
    def header(self):
        if self.page_no() <= 2:
            return
        self.set_draw_color(*LINE)
        self.set_line_width(0.3)
        self.line(self.l_margin, 13, self.w - self.r_margin, 13)
        self.set_font("Vazir", "", 8)
        self.set_text_color(*GRAY)
        self.set_xy(self.l_margin, 6)
        self.cell(self.epw, 6, "جزوهٔ شب امتحانی | آداب پزشکی ۱", align="R")
        self.set_xy(self.l_margin, 6)
        self.cell(self.epw, 6, "دانشگاه علوم پزشکی هرمزگان", align="L")
        self.set_y(18)

    def footer(self):
        if self.page_no() <= 1:
            return
        self.set_y(-14)
        self.set_draw_color(*LINE)
        self.set_line_width(0.3)
        self.line(self.l_margin, self.get_y(), self.w - self.r_margin, self.get_y())
        # شمارهٔ صفحه (وسط)
        self.set_font("Vazir", "", 9)
        self.set_text_color(*TEAL_DARK)
        self.set_xy(self.l_margin, -14)
        self.cell(self.epw, 9, f"{self.page_no()}", align="C")
        # برند HumsYar (چپ)
        self.set_xy(self.l_margin, -14)
        self.set_font("Vazir", "B", 9.5)
        self.set_text_color(*NAVY)
        hw = self.get_string_width("Hums")
        self.cell(hw, 9, "Hums", align="L")
        self.set_text_color(*TEAL)
        self.cell(14, 9, "Yar", align="L")
        # شعار (راست)
        self.set_xy(self.l_margin, -14)
        self.set_font("Vazir", "", 7.5)
        self.set_text_color(*GRAY)
        self.cell(self.epw, 9, "دستیار هوشمند دانشجویان پزشکی", align="R")

    # ---------- ابزارهای کمکی ----------
    @property
    def eph_avail(self):
        return self.page_break_trigger - self.t_margin

    def need(self, h):
        if self.get_y() + h > self.page_break_trigger:
            self.add_page()

    def keep(self, h):
        """تضمین اینکه بلوکی به ارتفاع h یکجا در صفحه بماند (در حد ظرفیت یک صفحه)."""
        self.need(min(h, self.eph_avail - 6))

    def est_list(self, items, indent=0, mw=7, size=BODY):
        """برآورد ارتفاع یک فهرست (برای صفحه‌بندی تمیز)."""
        self.set_font("Vazir", "", size)
        total = 0.0
        for it in items:
            total += self.multi_cell(self.epw - indent - mw, LH, it, align="R",
                                     dry_run=True, output="HEIGHT") + 0.4
        return total + 1

    def est_tags(self, items, size=9.5):
        self.set_font("Vazir", "B", size)
        x_avail = self.epw
        rows, used = 1, 0.0
        for it in items:
            tw = self.get_string_width(it) + 7 + 2.5
            if used + tw > x_avail and used > 0:
                rows += 1
                used = 0.0
            used += tw
        return rows * 10 + 1

    def chapter(self, title, subtitle="", num_char=None):
        self.chapter_no += 1
        self.add_page()
        label = num_char or CH_DIGITS[self.chapter_no - 1]
        toc_title = title if num_char else f"فصل {label} — {title}"
        self.toc.append((toc_title, self.page_no()))
        y = self.get_y()
        self.set_fill_color(*NAVY)
        self.rect(self.l_margin, y, self.epw, 17, style="F", round_corners=True, corner_radius=2.5)
        self.set_fill_color(*GOLD)
        cx = self.w - self.r_margin - 8.5
        self.ellipse(cx - 5.5, y + 3, 11, 11, style="F")
        self.set_font("VazirBlack", "", 13)
        self.set_text_color(*NAVY)
        self.set_xy(cx - 5.5, y + 3)
        self.cell(11, 11, label, align="C")
        self.set_font("VazirBlack", "", 14.5)
        self.set_text_color(*WHITE)
        self.set_xy(self.l_margin, y)
        self.cell(self.epw - 18, 17, title, align="R")
        self.set_y(y + 17)
        if subtitle:
            self.ln(1.5)
            self.set_font("Vazir", "", 9.5)
            self.set_text_color(*GRAY)
            self.cell(self.epw, 6, subtitle, align="R", new_x=XPos.LMARGIN, new_y=YPos.NEXT)
        self.ln(4)

    def h2(self, text, keep=0):
        self.need(20 + keep if keep else 20)
        self.ln(2.5)
        y = self.get_y()
        self.set_fill_color(*TEAL)
        self.rect(self.w - self.r_margin - 2.6, y + 1.2, 2.6, 7.6, style="F",
                  round_corners=True, corner_radius=1)
        self.set_font("Vazir", "B", 12.5)
        self.set_text_color(*TEAL_DARK)
        self.set_xy(self.l_margin, y)
        self.cell(self.epw - 5.5, 10, text, align="R", new_x=XPos.LMARGIN, new_y=YPos.NEXT)
        self.set_draw_color(*LINE)
        self.set_line_width(0.25)
        self.line(self.l_margin, self.get_y() + 0.4, self.w - self.r_margin, self.get_y() + 0.4)
        self.ln(2.6)

    def h3(self, text, keep=0):
        self.keep(14 + keep)
        self.ln(1)
        y = self.get_y()
        self.set_fill_color(*GOLD)
        self.rect(self.w - self.r_margin - 3.6, y + 2.2, 3.1, 3.1, style="F",
                  round_corners=True, corner_radius=0.7)
        self.set_font("Vazir", "B", 11)
        self.set_text_color(*NAVY)
        self.set_xy(self.l_margin, y)
        self.cell(self.epw - 7, 7.5, text, align="R", new_x=XPos.LMARGIN, new_y=YPos.NEXT)
        self.ln(0.6)

    def p(self, text, size=BODY):
        self.set_font("Vazir", "", size)
        self.set_text_color(30, 36, 45)
        self.multi_cell(self.epw, LH, text, align="R", new_x=XPos.LMARGIN, new_y=YPos.NEXT)
        self.ln(1.2)

    def bullet(self, text, indent=0, marker="●", mcolor=TEAL, bold=False):
        self.set_font("Vazir", "B" if bold else "", BODY)
        mw = 7
        h = self.multi_cell(self.epw - indent - mw, LH, text, align="R",
                            dry_run=True, output="HEIGHT")
        self.need(h + 1)
        y0 = self.get_y()
        mx = self.w - self.r_margin - indent - mw
        if marker == "●":
            self.set_fill_color(*mcolor)
            self.ellipse(mx + mw / 2 - 1.1, y0 + LH / 2 - 1.1, 2.2, 2.2, style="F")
        else:
            self.set_text_color(*mcolor)
            self.set_font("Vazir", "B", BODY)
            self.set_xy(mx, y0)
            self.cell(mw, LH, marker, align="C")
        self.set_font("Vazir", "B" if bold else "", BODY)
        self.set_text_color(30, 36, 45)
        self.set_xy(self.l_margin, y0)
        self.multi_cell(self.epw - indent - mw, LH, text, align="R",
                        new_x=XPos.LMARGIN, new_y=YPos.NEXT)
        self.ln(0.4)

    def bullets(self, items, indent=0):
        for it in items:
            self.bullet(it, indent=indent)
        self.ln(1)

    def numbered(self, items, indent=0):
        for i, it in enumerate(items):
            self.bullet(it, indent=indent, marker=NUM_DIGITS[i] + ".", mcolor=TEAL_DARK)
        self.ln(1)

    # — نسخه‌های «یکجا بمان» —
    def h3_bullets(self, title, items, indent=3):
        self.h3(title, keep=self.est_list(items, indent))
        self.bullets(items, indent=indent)

    def h3_numbered(self, title, items, indent=0):
        self.h3(title, keep=self.est_list(items, indent))
        self.numbered(items, indent=indent)

    def h2_bullets(self, title, items, indent=0):
        self.h2(title, keep=self.est_list(items, indent))
        self.bullets(items, indent=indent)

    def h2_numbered(self, title, items, indent=0):
        self.h2(title, keep=self.est_list(items, indent))
        self.numbered(items, indent=indent)

    def note(self, text, title="نکتهٔ شب امتحان", fill=GOLD_LIGHT, bar=GOLD, tcolor=(130, 90, 10)):
        self.set_font("Vazir", "", 9.8)
        pad = 4
        w = self.epw - 2 * pad - 4
        th = self.multi_cell(w, 6, text, align="R", dry_run=True, output="HEIGHT")
        box_h = th + 2 * pad + 7
        self.keep(box_h + 3)
        y0 = self.get_y()
        self.set_fill_color(*fill)
        self.rect(self.l_margin, y0, self.epw, box_h, style="F",
                  round_corners=True, corner_radius=2)
        self.set_fill_color(*bar)
        self.rect(self.w - self.r_margin - 2.6, y0, 2.6, box_h, style="F",
                  round_corners=True, corner_radius=1.3)
        self.set_font("Vazir", "B", 10)
        self.set_text_color(*tcolor)
        self.set_xy(self.l_margin + pad, y0 + pad - 1.5)
        self.cell(w, 7, "« " + title + " »", align="R")
        self.set_font("Vazir", "", 9.8)
        self.set_text_color(60, 50, 25) if bar == GOLD else self.set_text_color(70, 30, 25)
        self.set_xy(self.l_margin + pad, y0 + pad + 6)
        self.multi_cell(w, 6, text, align="R")
        self.set_y(y0 + box_h)
        self.ln(3)

    def warn(self, text, title="حواست باشد!"):
        self.note(text, title=title, fill=RED_LIGHT, bar=RED, tcolor=RED)

    def table_rtl(self, headers, rows, widths=None, size=9.3):
        headers = list(reversed(headers))
        rows = [list(reversed(r)) for r in rows]
        if widths:
            widths = list(reversed(widths))
        self.set_font("Vazir", "", size)
        self.set_draw_color(*LINE)
        self.set_line_width(0.2)
        self.set_fill_color(*WHITE)
        self.set_text_color(30, 36, 45)
        with self.table(
            col_widths=widths or None,
            text_align="RIGHT",
            borders_layout="HORIZONTAL_LINES",
            line_height=6.2,
            padding=1.6,
            headings_style=FontFace(emphasis="BOLD", color=WHITE, fill_color=TEAL_DARK),
            cell_fill_color=(243, 247, 249),
            cell_fill_mode="EVEN_ROWS",
        ) as table:
            hr = table.row()
            for h_ in headers:
                hr.cell(h_)
            for r in rows:
                row = table.row()
                for c in r:
                    row.cell(c)
        self.ln(2)

    def tag_line(self, items, fill=TEAL_LIGHT, tcolor=TEAL_DARK):
        """برچسب‌های رنگی راست‌به‌چپ — با محاسبهٔ سطرها قبل از رسم (بدون باگ شکست صفحه)."""
        self.set_font("Vazir", "B", 9.5)
        rows, row, x_used = [], [], 0.0
        for it in items:
            tw = self.get_string_width(it) + 7
            if x_used + tw > self.epw and row:
                rows.append(row)
                row, x_used = [], 0.0
            row.append((it, tw))
            x_used += tw + 2.5
        if row:
            rows.append(row)
        total_h = len(rows) * 10 + 1
        self.keep(total_h)
        y = self.get_y()
        for r in rows:
            x_right = self.w - self.r_margin
            for it, tw in r:
                self.set_fill_color(*fill)
                self.rect(x_right - tw, y, tw, 8, style="F",
                          round_corners=True, corner_radius=2.5)
                self.set_text_color(*tcolor)
                self.set_xy(x_right - tw, y)
                self.cell(tw, 8, it, align="C")
                x_right -= tw + 2.5
            y += 10
        self.set_y(y + 1)


