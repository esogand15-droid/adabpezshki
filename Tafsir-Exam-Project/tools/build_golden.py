def fa(n):
    return str(n).translate(str.maketrans("0123456789", "۰۱۲۳۴۵۶۷۸۹"))

# ---------------------------------------------------------------- engine
def text_h(txt, w, size, lh=LH, bullet=False):
    pdf.set_font("Vazir", "", size)
    t = ("• " + txt) if bullet else txt
    lines = pdf.multi_cell(w, lh, t, align="R", dry_run=True, output="LINES")
    return len(lines) * lh

def card_height(key, w):
    cw = w - 2 * PAD
    h = 7.6  # header strip
    h += 1.6  # top gap
    for si, (label, items) in enumerate(CARDS[key]["secs"]):
        h += 3.6  # section label
        for it in items:
            h += text_h(it, cw, BODY, bullet=(len(items) > 1)) + 0.35
        h += 1.5  # divider spacing
    h += 0.8
    return h

def draw_card(key, x, y, w):
    c = SURA_COLORS[key]
    card = CARDS[key]
    h = card_height(key, w)
    # body bg
    pdf.set_fill_color(*c["tint"])
    pdf.set_draw_color(*c["main"])
    pdf.set_line_width(0.25)
    pdf.rect(x, y, w, h, "DF", round_corners=True, corner_radius=1.6)
    # header strip
    pdf.set_fill_color(*c["main"])
    pdf.rect(x, y, w, 7.6, "F", round_corners=("TOP_LEFT", "TOP_RIGHT"), corner_radius=1.6)
    pdf.set_text_color(255, 255, 255)
    pdf.set_font("Vazir", "B", 10.2)
    pdf.set_xy(x + PAD, y + 1.1)
    pdf.cell(w - 2 * PAD, 5.4, card["title"], align="R")
    pdf.set_font("VazirM", "", 7.2)
    pdf.set_xy(x + PAD, y + 1.9)
    pdf.cell(w - 2 * PAD, 3.8, card["badge"], align="L")
    # body
    cw = w - 2 * PAD
    cy = y + 7.6 + 1.6
    for si, (label, items) in enumerate(card["secs"]):
        pdf.set_text_color(*c["main"])
        pdf.set_font("Vazir", "B", 8.0)
        pdf.set_xy(x + PAD, cy)
        pdf.cell(cw, 3.4, label, align="R")
        cy += 3.6
        pdf.set_text_color(*TEXT)
        pdf.set_font("Vazir", "", BODY)
        for it in items:
            t = ("• " + it) if len(items) > 1 else it
            pdf.set_xy(x + PAD, cy)
            pdf.multi_cell(cw, LH, t, align="R")
            cy = pdf.get_y() + 0.35
        if si < len(card["secs"]) - 1:
            pdf.set_draw_color(*GREY_LINE)
            pdf.set_line_width(0.15)
            pdf.line(x + PAD + 4, cy + 0.55, x + w - PAD - 4, cy + 0.55)
        cy += 1.5
    return h

